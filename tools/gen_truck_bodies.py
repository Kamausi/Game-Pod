#!/usr/bin/env python3
"""Lofted body shells for the drivable trucks.

Replaces each truck's slab side-profile extrudes with designed sections lofted nose to tail:
rocker roll-under, a barrelled lower door, a soft character crease under the shoulder, a rounded
shoulder and a crowned hood; pickups get lofted bed-side panels with a rolled rail. Wheel
openings are clipped exactly with `cut` and backed by wheelhouse liners. The generated block is
written between `# >>> body shell` / `# <<< body shell` markers in each part (inserted in place of
the old extrude lines the first time). Run from the repo root: python3 tools/gen_truck_bodies.py
"""
import re

def half_flat(w, yb, yt, crown):
    """XJ/MJ-style section: flat panels, tight rocker roll, a hard character crease at handle height."""
    h = yt - yb
    yc = yb + 0.70 * h
    pts = [(0, yb), (w - 0.05, yb), (w - 0.008, yb + 0.04), (w, yb + 0.25 * h), (w + 0.002, yc - 0.012),
           (w + 0.009, yc), (w + 0.001, yc + 0.012), (w - 0.006, yt - 0.04), (w - 0.03, yt - 0.005),
           (w - 0.06, yt), (w * 0.5, yt + crown * 0.75), (0, yt + crown)]
    return ",".join(f"{x:.4f},{y:.4f}" for x, y in pts)

def half(w, yb, yt, crown):
    """Half section (x >= 0), bottom centre round to top centre."""
    h = yt - yb
    pts = [(0, yb), (w - 0.07, yb), (w - 0.012, yb + 0.06), (w, yb + 0.32 * h),
           (w + 0.004, yt - 0.17), (w - 0.006, yt - 0.13), (w - 0.022, yt - 0.05),
           (w - 0.07, yt - 0.008), (w * 0.5, yt + crown * 0.75), (0, yt + crown)]
    return ",".join(f"{x:.4f},{y:.4f}" for x, y in pts)

def bedside(hw, yb, yt):
    """Closed bed-side section (x > 0): outer skin, rolled rail, inner wall."""
    pts = [(hw - 0.07, yb + 0.01), (hw - 0.07, yb), (hw - 0.012, yb + 0.06), (hw, yb + 0.30 * (yt - yb)),
           (hw + 0.004, yt - 0.17), (hw - 0.006, yt - 0.13), (hw - 0.02, yt - 0.04), (hw - 0.05, yt),
           (hw - 0.12, yt), (hw - 0.12, yt - 0.05), (hw - 0.07, yt - 0.07)]
    return ",".join(f"{x:.4f},{y:.4f}" for x, y in pts)

def bedside_flat(hw, yb, yt, yc):
    """Flat bed side carrying the cab's character crease (yc) through to the tail."""
    pts = [(hw - 0.07, yb + 0.01), (hw - 0.07, yb), (hw - 0.008, yb + 0.04), (hw, yb + 0.12), (hw + 0.002, yc - 0.012),
           (hw + 0.009, yc), (hw + 0.001, yc + 0.012), (hw - 0.004, yt - 0.04), (hw - 0.03, yt - 0.003),
           (hw - 0.05, yt), (hw - 0.12, yt), (hw - 0.12, yt - 0.05), (hw - 0.07, yt - 0.07)]
    return ",".join(f"{x:.4f},{y:.4f}" for x, y in pts)

def block(T):
    L = ["# >>> body shell (generated by tools/gen_truck_bodies.py)",
         "# Lofted lower body: rocker roll-under, barrelled door, character crease, rounded shoulder,",
         "# crowned hood; wheel openings clipped exactly and backed by wheelhouse liners.",
         "color paint_r paint_g paint_b", "material paint"]
    hf = half_flat if T.get('style') == 'flat' else half
    secs = "|".join(f"{z}:{hf(w, yb, yt, c)}" for z, w, yb, yt, c in T['body'])
    L.append(f"loft sec={secs} n=3 m=2")
    hw = T['W'] / 2
    xmin = hw - 0.26
    def arch(A):   # (zc, yc, r) circle or (zc, yc, a, b, p) squared superellipse
        return A if len(A) == 5 else (A[0], A[1], A[2], A[2], 2)
    for A in T['arches_body']:
        zc, yc, a, b, pe = arch(A)
        L.append(f"cut cyl={zc},{yc},{a},{b} p={pe} xmin={xmin:.3f}")
    if T.get('bed'):
        z0, z1, yb, yt = T['bed']
        st = [z0, z0 - 0.04, z1 + 0.04, z1]
        if T.get('style') == 'flat':
            b0 = T['body'][2]   # a full-height cab station: crease height matches the cab's
            yc = b0[2] + 0.70 * (b0[3] - b0[2])
            secs = "|".join(f"{z:.3f}:{bedside_flat(hw, yb, yt, yc)}" for z in st)
        else:
            secs = "|".join(f"{z:.3f}:{bedside(hw, yb, yt)}" for z in st)
        L.append("# Lofted bed sides with a rolled rail and inner wall")
        L.append(f"loft full=1 sec={secs} n=2 m=2 mirror=x")
        for A in T['arches_bed']:
            zc, yc, a, b, pe = arch(A)
            L.append(f"cut cyl={zc},{yc},{a},{b} p={pe} xmin={xmin:.3f}")
    L += ["# Wheelhouse liners and inner walls", "color #121212", "material matte"]
    for A in T['arches_body'] + T.get('arches_bed', []):
        zc, yc, a, b, pe = arch(A)
        L.append(f"liner r={a - 0.004:.3f} b={b - 0.004:.3f} p={pe} w=0.27 a0=-8 a1=188 seg=24 pos={hw - 0.13:.3f},{yc},{zc} mirror=x")
        L.append(f"extrude depth=0.01 pts=sarc({zc},{yc},{a},{b},{pe},-8,188,24) pos={hw - 0.265:.3f},0,0 mirror=x")
    L += ["color paint_r paint_g paint_b", "material paint", "# <<< body shell"]
    return "\n".join(L)

