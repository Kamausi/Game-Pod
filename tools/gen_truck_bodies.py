def apply(name, T):
    p = f"cad/parts/vehicles/{name}.mbcad"
    s = open(p).read()
    blk = block(T)
    if "# >>> body shell" in s:
        s = re.sub(r"# >>> body shell.*?# <<< body shell", blk, s, flags=re.S)
    else:
        first = None
        for pat in T['remove']:
            m = re.search(pat, s, flags=re.M)
            if not m:
                raise SystemExit(f"{name}: pattern not found: {pat}")
            if first is None or m.start() < first:
                first = m.start()
        s = s[:first] + "@@BODY@@\n" + s[first:]
        for pat in T['remove']:
            s = re.sub(pat, "", s, count=1, flags=re.M)
        s = s.replace("@@BODY@@\n", blk + "\n", 1)
    s = re.sub(r"^deform .*$", T['deform'], s, count=1, flags=re.M)
    open(p, "w").write(s)
    print("wrote", name)

if __name__ == "__main__":
    import sys
    for n in (sys.argv[1:] or TRUCKS):
        apply(n, TRUCKS[n])
